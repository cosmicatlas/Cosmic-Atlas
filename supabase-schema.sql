-- Row Level Security is enabled. Never put a service_role key in the website.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null check (char_length(username) between 3 and 24),
  bio text not null default '' check (char_length(bio) <= 240),
  created_at timestamptz not null default now()
);
create unique index if not exists profiles_username_lower_unique on public.profiles (lower(username));

create table if not exists public.discussions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 5 and 140),
  body text not null check (char_length(body) between 1 and 6000),
  chapter_number integer,
  created_at timestamptz not null default now()
);
create index if not exists discussions_created_at_idx on public.discussions (created_at desc);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  discussion_id bigint not null references public.discussions(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);
create index if not exists comments_discussion_id_idx on public.comments (discussion_id, created_at);

alter table public.profiles enable row level security;
alter table public.discussions enable row level security;
alter table public.comments enable row level security;

drop policy if exists "Profiles are public to read" on public.profiles;
create policy "Profiles are public to read" on public.profiles for select using (true);
drop policy if exists "Users create own profile" on public.profiles;
create policy "Users create own profile" on public.profiles for insert to authenticated with check (auth.uid() = id);
drop policy if exists "Users update own profile" on public.profiles;
create policy "Users update own profile" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "Discussions are public to read" on public.discussions;
create policy "Discussions are public to read" on public.discussions for select using (true);
drop policy if exists "Signed-in users create discussions as themselves" on public.discussions;
create policy "Signed-in users create discussions as themselves" on public.discussions for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Authors update own discussions" on public.discussions;
create policy "Authors update own discussions" on public.discussions for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Authors delete own discussions" on public.discussions;
create policy "Authors delete own discussions" on public.discussions for delete to authenticated using (auth.uid() = user_id);

drop policy if exists "Comments are public to read" on public.comments;
create policy "Comments are public to read" on public.comments for select using (true);
drop policy if exists "Signed-in users create comments as themselves" on public.comments;
create policy "Signed-in users create comments as themselves" on public.comments for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Authors update own comments" on public.comments;
create policy "Authors update own comments" on public.comments for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Authors delete own comments" on public.comments;
create policy "Authors delete own comments" on public.comments for delete to authenticated using (auth.uid() = user_id);

grant select on public.profiles, public.discussions, public.comments to anon, authenticated;
grant insert, update on public.profiles to authenticated;
grant insert, update, delete on public.discussions, public.comments to authenticated;
grant usage, select on all sequences in schema public to authenticated;


-- Reddit-style public communities (groups) and membership.
create table if not exists public.communities (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 3 and 40),
  slug text not null unique check (slug ~ '^[a-z0-9-]{3,40}$'),
  description text not null default '' check (char_length(description) <= 300),
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create index if not exists communities_created_at_idx on public.communities (created_at desc);

create table if not exists public.community_members (
  community_id bigint not null references public.communities(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (community_id, user_id)
);
create index if not exists community_members_user_idx on public.community_members (user_id);

alter table public.discussions add column if not exists community_id bigint references public.communities(id) on delete cascade;
create index if not exists discussions_community_created_idx on public.discussions (community_id, created_at desc);

alter table public.communities enable row level security;
alter table public.community_members enable row level security;

drop policy if exists "Communities are public to read" on public.communities;
create policy "Communities are public to read" on public.communities for select using (true);
drop policy if exists "Signed-in users create communities" on public.communities;
create policy "Signed-in users create communities" on public.communities for insert to authenticated with check (auth.uid() = created_by);
drop policy if exists "Creators update their communities" on public.communities;
create policy "Creators update their communities" on public.communities for update to authenticated using (auth.uid() = created_by) with check (auth.uid() = created_by);
drop policy if exists "Creators delete their communities" on public.communities;
create policy "Creators delete their communities" on public.communities for delete to authenticated using (auth.uid() = created_by);

drop policy if exists "Community memberships are public to read" on public.community_members;
create policy "Community memberships are public to read" on public.community_members for select using (true);
drop policy if exists "Users join as themselves" on public.community_members;
create policy "Users join as themselves" on public.community_members for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Users leave their communities" on public.community_members;
create policy "Users leave their communities" on public.community_members for delete to authenticated using (auth.uid() = user_id);

drop policy if exists "Signed-in users create discussions as themselves" on public.discussions;
create policy "Signed-in users create discussions as themselves" on public.discussions for insert to authenticated
with check (
  auth.uid() = user_id and
  (community_id is null or exists (
    select 1 from public.community_members m
    where m.community_id = discussions.community_id and m.user_id = auth.uid()
  ))
);

grant select on public.communities, public.community_members to anon, authenticated;
grant insert, update, delete on public.communities to authenticated;
grant insert, delete on public.community_members to authenticated;
grant usage, select on all sequences in schema public to authenticated;
